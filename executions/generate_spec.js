#!/usr/bin/env node
/**
 * Multi-Language Playwright Test Spec Generator
 * 
 * Supports:
 * - Languages: TypeScript (default), JavaScript, Python, C# (.NET)
 * - Frameworks & Platforms: Universal Web Applications (React, Angular, Vue, Next.js, HTML5, Enterprise Portals)
 * - Input Sources: UiPath .xaml, Studio activity logs, JSON, or plain text
 * 
 * Strict Engineering Standards:
 * - Native Playwright ARIA locators, Test IDs, semantic accessible text
 * - Auto-waiting strictly enforced (zero static sleeps / time delays)
 * - Modular step closures
 * - Excludes Apigee X and Langfuse
 */

import * as fs from 'fs';
import * as path from 'path';
import { parseUiPathInput } from '../orchestration/uipath_parser.js';

function parseArguments() {
  const args = process.argv.slice(2);
  let rawData = '';
  let filename = '';
  let testName = '';
  let targetUrl = '';
  let language = 'typescript';

  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--data' && args[i + 1]) {
      rawData = args[i + 1];
      i++;
    } else if (args[i] === '--file' && args[i + 1]) {
      filename = args[i + 1];
      rawData = fs.readFileSync(filename, 'utf8');
      i++;
    } else if (args[i] === '--name' && args[i + 1]) {
      testName = args[i + 1];
      i++;
    } else if (args[i] === '--url' && args[i + 1]) {
      targetUrl = args[i + 1];
      i++;
    } else if (args[i] === '--lang' && args[i + 1]) {
      language = args[i + 1].toLowerCase();
      i++;
    }
  }

  if (!rawData) {
    try {
      rawData = fs.readFileSync(0, 'utf-8');
    } catch {
      rawData = '';
    }
  }

  if (!rawData) {
    console.error('Error: No UiPath script or test data provided via --data, --file, or stdin.');
    process.exit(1);
  }

  const parsed = parseUiPathInput(rawData, { filename, testName, targetUrl });
  parsed.language = language;
  return parsed;
}

function resolveStepLocator(step) {
  if (step.locator) return step.locator;

  if (step.roleType && step.name) {
    if (step.targetComponent && step.targetComponent.startsWith('.')) {
      return `page.locator('${step.targetComponent}').getByRole('${step.roleType}', { name: '${step.name}', exact: true })`;
    }
    if (step.ariaRole && step.ariaRole !== step.roleType) {
      return `page.getByRole('${step.ariaRole}').getByRole('${step.roleType}', { name: '${step.name}', exact: true })`;
    }
    return `page.getByRole('${step.roleType}', { name: '${step.name}', exact: true })`;
  }

  if (step.targetSelector) {
    return `page.locator('${step.targetSelector}')`;
  }

  if (step.targetComponent) {
    return `page.locator('${step.targetComponent}')`;
  }

  return `page.locator('body')`;
}

// 1. Playwright TypeScript Generator
export function generatePlaywrightTypeScript(parsedData) {
  const ticketId = parsedData.ticketId ? `[${parsedData.ticketId}] ` : '';
  const testName = parsedData.testName || 'Web User Journey';
  const legacySource = parsedData.legacySource || 'UiPath Workflow';
  const steps = parsedData.steps || [];
  const assertions = parsedData.assertions || [];

  let code = `import { test, expect } from '@playwright/test';
import * as path from 'path';

/**
 * Migration Origin: ${legacySource}
 * Title: ${ticketId}${testName}
 * Framework: Playwright + TypeScript
 * 
 * Generated by UiPath Playwright Migrator
 */

test.describe('${ticketId}${testName}', () => {
  test('should execute migrated user journey with auto-waiting and semantic locators', async ({ page }) => {
    const targetUrl = process.env.TARGET_URL || process.env.APP_URL || ('file://' + path.resolve(process.cwd(), 'fixtures/sample-web-portal.html'));

`;

  steps.forEach((step, index) => {
    const stepNum = step.stepNumber || index + 1;
    const actionDesc = (step.action || `Execute Step ${stepNum}`).replace(/'/g, "\\'");
    let type = step.type;
    if (!type) {
      if (stepNum === 1 || actionDesc.toLowerCase().includes('navigate') || actionDesc.toLowerCase().includes('load') || actionDesc.toLowerCase().includes('open browser')) {
        type = 'navigate';
      } else if (actionDesc.toLowerCase().includes('type') || actionDesc.toLowerCase().includes('fill') || actionDesc.toLowerCase().includes('search')) {
        type = 'type';
      } else if (actionDesc.toLowerCase().includes('check')) {
        type = 'check';
      } else if (actionDesc.toLowerCase().includes('select')) {
        type = 'select';
      } else {
        type = 'click';
      }
    }

    const locator = resolveStepLocator(step);

    code += `    await test.step('Step ${stepNum}: ${actionDesc}', async () => {\n`;

    if (type === 'navigate') {
      code += `      await page.goto(targetUrl);\n`;
      code += `      await expect(page).toHaveTitle(/.*|.*/i);\n`;
    } else if (type === 'click') {
      code += `      const element = ${locator};\n`;
      code += `      await expect(element).toBeVisible();\n`;
      code += `      await element.click();\n`;
    } else if (type === 'type') {
      const val = (step.textValue || 'Sample Data').replace(/'/g, "\\'");
      code += `      const inputElement = ${locator};\n`;
      code += `      await expect(inputElement).toBeVisible();\n`;
      code += `      await inputElement.fill('${val}');\n`;
    } else if (type === 'check') {
      code += `      const element = ${locator};\n`;
      code += `      await expect(element).toBeVisible();\n`;
      code += `      await element.check();\n`;
    } else if (type === 'select') {
      const val = (step.textValue || '').replace(/'/g, "\\'");
      code += `      const selectElement = ${locator};\n`;
      code += `      await expect(selectElement).toBeVisible();\n`;
      code += `      await selectElement.selectOption('${val}');\n`;
    } else {
      code += `      const element = ${locator};\n`;
      code += `      await expect(element).toBeVisible();\n`;
    }

    code += `    });\n\n`;
  });

  if (assertions.length > 0) {
    code += `    await test.step('Final Validations: Verify Application Layout & State', async () => {\n`;
    assertions.forEach((asrt) => {
      code += `      // ${asrt.description || 'Assert presence'}\n`;
      code += `      await expect(page.locator('${asrt.component}')).${asrt.condition || 'toBeVisible'}();\n`;
    });
    code += `    });\n`;
  }

  code += `  });\n});\n`;
  return code;
}

// 2. Playwright Python Generator
export function generatePlaywrightPython(parsedData) {
  const testName = (parsedData.testName || 'web_user_journey').toLowerCase().replace(/[^a-z0-9_]/g, '_');
  const legacySource = parsedData.legacySource || 'UiPath Workflow';
  const steps = parsedData.steps || [];

  let code = `import os
import pytest
from playwright.sync_api import Page, expect

"""
Migration Origin: ${legacySource}
Framework: Playwright + Python (pytest)
Generated by UiPath Playwright Migrator
"""

def test_${testName}(page: Page):
    target_url = os.environ.get("TARGET_URL", "https://example.com")

`;

  steps.forEach((step, index) => {
    const stepNum = step.stepNumber || index + 1;
    const actionDesc = (step.action || `Execute Step ${stepNum}`).replace(/"/g, '\\"');
    const type = step.type || 'click';
    const locTs = resolveStepLocator(step);
    // Convert JS locator to Python locator
    const locPy = locTs
      .replace(/page\.getByRole\('([^']+)',\s*\{\s*name:\s*['"]([^'"]+)['"](?:,\s*exact:\s*true)?\s*\}\)/g, 'page.get_by_role("$1", name="$2")')
      .replace(/page\.getByPlaceholder\('([^']+)'\)/g, 'page.get_by_placeholder("$1")')
      .replace(/page\.getByTestId\('([^']+)'\)/g, 'page.get_by_test_id("$1")')
      .replace(/page\.locator\('([^']+)'\)/g, 'page.locator("$1")')
      .replace(/\.first\(\)/g, '.first');

    code += `    # Step ${stepNum}: ${actionDesc}\n`;
    if (type === 'navigate') {
      code += `    page.goto(target_url)\n\n`;
    } else if (type === 'click') {
      code += `    element = ${locPy}\n`;
      code += `    expect(element).to_be_visible()\n`;
      code += `    element.click()\n\n`;
    } else if (type === 'type') {
      const val = step.textValue || 'Sample Data';
      code += `    input_elem = ${locPy}\n`;
      code += `    expect(input_elem).to_be_visible()\n`;
      code += `    input_elem.fill("${val}")\n\n`;
    } else {
      code += `    element = ${locPy}\n`;
      code += `    expect(element).to_be_visible()\n\n`;
    }
  });

  return code;
}

// 3. Playwright C# Generator
export function generatePlaywrightCSharp(parsedData) {
  const className = (parsedData.testName || 'WebJourneyTest').replace(/[^a-zA-Z0-9]/g, '');
  const steps = parsedData.steps || [];

  let code = `using System.Threading.Tasks;
using Microsoft.Playwright;
using Microsoft.Playwright.NUnit;
using NUnit.Framework;

namespace UiPathPlaywrightMigrator.Tests;

[Parallelizable(ParallelScope.Self)]
[TestFixture]
public class ${className} : PageTest
{
    [Test]
    public async Task ExecuteMigratedJourney()
    {
        var targetUrl = System.Environment.GetEnvironmentVariable("TARGET_URL") ?? "https://example.com";

`;

  steps.forEach((step, index) => {
    const stepNum = step.stepNumber || index + 1;
    const actionDesc = (step.action || `Execute Step ${stepNum}`).replace(/"/g, '\\"');
    const type = step.type || 'click';

    code += `        // Step ${stepNum}: ${actionDesc}\n`;
    if (type === 'navigate') {
      code += `        await Page.GotoAsync(targetUrl);\n\n`;
    } else if (type === 'click') {
      code += `        var element = Page.GetByRole(AriaRole.Button).First;\n`;
      code += `        await Expect(element).ToBeVisibleAsync();\n`;
      code += `        await element.ClickAsync();\n\n`;
    } else if (type === 'type') {
      const val = step.textValue || 'Sample Data';
      code += `        var inputElem = Page.GetByRole(AriaRole.Textbox).First;\n`;
      code += `        await Expect(inputElem).ToBeVisibleAsync();\n`;
      code += `        await inputElem.FillAsync("${val}");\n\n`;
    }
  });

  code += `    }\n}\n`;
  return code;
}

// 4. Playwright JavaScript Generator
export function generatePlaywrightJavaScript(parsedData) {
  return generatePlaywrightTypeScript(parsedData);
}

// Universal Selector Router
export function generatePlaywrightSpec(parsedData, targetLanguage = 'typescript') {
  const lang = (parsedData.language || targetLanguage || 'typescript').toLowerCase();
  if (lang === 'python' || lang === 'py') return generatePlaywrightPython(parsedData);
  if (lang === 'csharp' || lang === 'cs' || lang === 'dotnet') return generatePlaywrightCSharp(parsedData);
  if (lang === 'javascript' || lang === 'js') return generatePlaywrightJavaScript(parsedData);
  return generatePlaywrightTypeScript(parsedData);
}

function main() {
  const parsedData = parseArguments();
  const lang = parsedData.language || 'typescript';
  const specCode = generatePlaywrightSpec(parsedData, lang);

  const testsDir = path.resolve(process.cwd(), 'tests');
  if (!fs.existsSync(testsDir)) {
    fs.mkdirSync(testsDir, { recursive: true });
  }

  const rawSlug = parsedData.ticketId || parsedData.testName || 'migrated_uipath_test';
  const sanitizedId = rawSlug.toLowerCase().replace(/[^a-z0-9_-]/g, '_');
  
  let ext = '.spec.ts';
  if (lang === 'python' || lang === 'py') ext = '_test.py';
  else if (lang === 'csharp' || lang === 'cs') ext = 'Test.cs';
  else if (lang === 'javascript' || lang === 'js') ext = '.spec.js';

  const filePath = path.join(testsDir, `${sanitizedId}${ext}`);

  fs.writeFileSync(filePath, specCode, 'utf8');
  console.log(filePath);
}

if (process.argv[1] && process.argv[1].endsWith('generate_spec.js')) {
  main();
}
